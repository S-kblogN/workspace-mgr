#[test]
fn scaffold_reconciliation_preserves_a_managed_local_only_block() {
    let fixture = GitFixture::new();
    workspace(&fixture.seed, ["manage"]);
    fixture.commit_seed("Initialize workspace");
    fixture.clone_shared();
    workspace(
        &fixture.shared,
        [
            "task",
            "create",
            "local-block",
            "--title",
            "Local block",
            "--purpose",
            "Keep a managed local-only rule across reconciliation.",
            "--timestamp",
            "20260829-171500",
        ],
    );
    let task = fixture.shared.join("20260829-171500-local-block");
    std::fs::write(task.join("data.bin"), b"local bytes").unwrap();
    workspace(&task, ["untrack", "20260829-171500-local-block/data.bin"]);

    // Take the block exactly as `untrack` writes it, so this fixture cannot
    // drift from the real writer's format.
    let written = std::fs::read_to_string(task.join(".gitignore")).unwrap();
    let begin = written.find("# workspace-mgr local begin").unwrap();
    let block = format!("\n{}", &written[begin..]);
    let root_ignore = fixture.shared.join(".gitignore");
    let generated = std::fs::read_to_string(&root_ignore).unwrap();
    std::fs::write(&root_ignore, format!("{generated}{block}")).unwrap();
    assert_eq!(
        json(&workspace(&fixture.shared, ["doctor"]))["status"],
        "ok"
    );

    // Drift elsewhere in the file is repaired while the block survives.
    std::fs::write(
        &root_ignore,
        format!("{generated}# hand edited\n/stale{block}"),
    )
    .unwrap();
    let repaired = workspace(&fixture.shared, ["manage"]);
    assert_eq!(json(&repaired)["status"], "managed");
    let reconciled = std::fs::read_to_string(&root_ignore).unwrap();
    assert!(!reconciled.contains("/stale"), "{reconciled}");
    assert!(reconciled.contains(".DS_Store"));
    assert!(reconciled.ends_with(&block), "{reconciled}");
    assert_eq!(
        json(&workspace(&fixture.shared, ["doctor"]))["status"],
        "ok"
    );

    // A marker without its partner has no readable extent. Refusing it would
    // wedge the one file the product can always rebuild, so regeneration drops
    // it and the report says which marker it dropped.
    std::fs::write(
        &root_ignore,
        format!("{generated}\n# workspace-mgr local begin 6461746162696e\n/data.bin\n"),
    )
    .unwrap();
    let repaired = workspace(&fixture.shared, ["manage"]);
    let repaired = json(&repaired);
    assert_eq!(repaired["status"], "managed");
    let detail = repaired["actions"]
        .as_array()
        .unwrap()
        .iter()
        .find(|action| action["path"] == ".gitignore")
        .unwrap_or_else(|| panic!("{repaired}"))["detail"]
        .as_str()
        .unwrap()
        .to_owned();
    assert!(
        detail.contains("dropped 1 unpaired managed local-only block marker")
            && detail.contains("# workspace-mgr local begin 6461746162696e"),
        "{detail}"
    );
    assert_eq!(std::fs::read_to_string(&root_ignore).unwrap(), generated);
    assert_eq!(
        json(&workspace(&fixture.shared, ["doctor"]))["status"],
        "ok"
    );
    assert_eq!(
        json(&workspace(&fixture.shared, ["manage"]))["status"],
        "no_changes"
    );
}

