#[test]
fn manage_instructions_doctor_and_task_create_form_one_workflow() {
    let fixture = GitFixture::new();
    fixture.clone_shared();

    let dry = workspace(
        &fixture.shared,
        [
            "manage",
            "--dry-run",
            "--repo",
            fixture.shared.to_str().unwrap(),
        ],
    );
    assert_eq!(json(&dry)["status"], "dry_run");
    assert!(!fixture.shared.join(".workspace-mgr.toml").exists());
    assert!(
        !fixture
            .shared
            .join(".workspace-mgr/local/repository.lock")
            .exists()
    );

    let initialized = workspace(
        &fixture.shared,
        ["manage", "--repo", fixture.shared.to_str().unwrap()],
    );
    assert_eq!(json(&initialized)["status"], "managed");
    assert!(fixture.shared.join(".workspace-mgr.toml").is_file());
    assert!(fixture.shared.join("AGENTS.md").is_file());
    let root_ignore = std::fs::read_to_string(fixture.shared.join(".gitignore")).unwrap();
    assert!(root_ignore.starts_with("# Generated by workspace-mgr."));
    assert!(root_ignore.contains(".workspace-mgr/repository.gitignore"));
    assert!(root_ignore.contains("\n.DS_Store\n"));
    assert!(root_ignore.contains("\nnode_modules/\n"));

    let repeated = workspace(
        &fixture.shared,
        ["manage", "--repo", fixture.shared.to_str().unwrap()],
    );
    assert_eq!(json(&repeated)["status"], "no_changes");

    let instructions = workspace(&fixture.shared, ["--format", "human", "instructions"]);
    let text = String::from_utf8(instructions.stdout).unwrap();
    let model = text.find("# How this workspace works").unwrap();
    let rules = text.find("# Effective repository instructions").unwrap();
    assert!(
        model < rules,
        "management model must precede operational rules"
    );
    let normalized_text = text.split_whitespace().collect::<Vec<_>>().join(" ");
    for global in [
        "one writable conversation (chat) = one task",
        "Effective repository instructions",
        "shared checkout",
        "Reading and ownership are separate",
        "default write boundary is its own task directory",
        "another chat's task directory",
        "explicit user authorization for the exact path and action",
        "do not manufacture it",
        "cloud-usage approval, CLI installation and updates",
        "before every writable-task turn",
        "task create --help",
        "archive --help",
        "policy=",
    ] {
        assert!(
            normalized_text.contains(global),
            "global instructions omit {global:?}"
        );
    }
    assert!(
        text.len() < 10_000,
        "default output grew into an operation manual"
    );
    for operation_detail in [
        "## Task lifecycle",
        "## Publication",
        "## Artifact hygiene",
        "## Storage placement",
        "## Repository infrastructure",
        "--historical-record",
        "small-s3-boundary",
        "source retirement",
        "1.25 GiB (1342177280 bytes)",
    ] {
        assert!(
            !text.contains(operation_detail),
            "default output leaked {operation_detail:?}"
        );
    }
    let explicit_all = workspace(
        &fixture.shared,
        ["--format", "human", "instructions", "all"],
    );
    assert_eq!(explicit_all.stdout, text.as_bytes());

    let model_only = workspace(
        &fixture.shared,
        ["--format", "human", "instructions", "model"],
    );
    let model_only = String::from_utf8(model_only.stdout).unwrap();
    assert!(model_only.contains("# How this workspace works"));
    assert!(!model_only.contains("# Effective repository instructions"));

    let doctor = workspace(&fixture.shared, ["--format", "json", "doctor"]);
    assert_eq!(json(&doctor)["status"], "ok");

    let created = workspace(
        &fixture.shared,
        [
            "task",
            "create",
            "sample-task",
            "--title",
            "Sample task",
            "--purpose",
            "Exercise deterministic scaffolding.",
            "--timestamp",
            "20260829-170000",
        ],
    );
    let payload = json(&created);
    assert_eq!(payload["status"], "created");
    assert_eq!(payload["task_id"], "20260829-170000-sample-task");
    assert_eq!(payload["review"]["pull_request"], "required");
    assert_eq!(
        payload["review"]["creation_timing"],
        "immediate-after-scaffold-publication"
    );
    assert_eq!(
        payload["review"]["synchronization_cadence"],
        "before-every-turn-end"
    );
    let task = fixture.shared.join("20260829-170000-sample-task");
    assert!(task.join("README.md").is_file());
    assert!(task.join(".workspace-mgr-task.toml").is_file());
    assert_eq!(
        payload["files"].as_array().unwrap(),
        &vec![
            serde_json::json!("20260829-170000-sample-task/README.md"),
            serde_json::json!("20260829-170000-sample-task/.workspace-mgr-task.toml"),
        ]
    );
    let readme = std::fs::read_to_string(task.join("README.md")).unwrap();
    assert!(readme.contains("## Directory map"));
    assert!(readme.contains(
        "- Keep this task's tools, process, decisions, and hard-to-reproduce results in this directory and list them here."
    ));
    let branch = git(
        &fixture.shared,
        ["rev-parse", "--verify", "codex/sample-task"],
    );
    assert!(!branch.stdout.is_empty());
}

#[test]
fn infrastructure_task_publishes_from_main_with_private_state_and_index() {
    let fixture = GitFixture::new();
    workspace(&fixture.seed, ["manage"]);
    fixture.commit_seed("Add workspace policy");
    fixture.clone_shared();

    let created = workspace(
        &fixture.shared,
        [
            "task",
            "create",
            "shared-policy",
            "--kind",
            "infrastructure",
            "--title",
            "Shared policy",
            "--purpose",
            "Update one repository-wide policy file.",
            "--scope",
            "shared-policy.md",
            "--scope-note",
            "The user requested this repository-wide policy change.",
        ],
    );
    let created = json(&created);
    assert_eq!(created["kind"], "infrastructure");
    assert_eq!(created["task_id"], "infra-shared-policy");
    assert_eq!(created["branch"], "codex/infra-shared-policy");
    assert_eq!(
        created["review"]["creation_timing"],
        "after-first-scoped-publication"
    );
    assert_eq!(
        created["review"]["synchronization_cadence"],
        "before-every-turn-end"
    );
    let worktree = std::path::PathBuf::from(created["path"].as_str().unwrap());
    let manifest = std::path::PathBuf::from(created["manifest"].as_str().unwrap());
    assert_eq!(worktree, fixture.shared.canonicalize().unwrap());
    assert!(worktree.is_dir());
    assert!(manifest.is_file());
    assert!(!fixture.shared.join("infra-shared-policy").exists());
    assert_eq!(
        String::from_utf8_lossy(&git(&worktree, ["branch", "--show-current"]).stdout).trim(),
        "main"
    );
    let main_before = git(&worktree, ["rev-parse", "HEAD"]).stdout;
    let index_before = git(&worktree, ["ls-files", "--stage"]).stdout;
    let worktrees_before = git(&worktree, ["worktree", "list", "--porcelain"]).stdout;
    let unselected = workspace_unchecked(&worktree, ["task", "status"]);
    assert_eq!(
        unselected.status.code(),
        Some(2),
        "private infrastructure tasks require explicit selection"
    );

    let status = workspace(
        &worktree,
        ["task", "status", "--manifest", manifest.to_str().unwrap()],
    );
    assert_eq!(json(&status)["kind"], "infrastructure");
    assert_eq!(
        json(&status)["scopes"],
        serde_json::json!(["shared-policy.md"])
    );
    let explicit = workspace(
        &fixture.shared,
        ["task", "status", "--manifest", manifest.to_str().unwrap()],
    );
    assert_eq!(json(&explicit)["branch"], "codex/infra-shared-policy");
    let doctor = workspace(&worktree, ["doctor"]);
    assert_eq!(json(&doctor)["status"], "ok");
    std::fs::write(worktree.join("shared-policy.md"), "shared policy\n").unwrap();
    std::fs::write(
        worktree.join("unrelated-overlay.txt"),
        "another task's unpublished bytes\n",
    )
    .unwrap();
    let published = workspace(
        &worktree,
        [
            "publish",
            "--manifest",
            manifest.to_str().unwrap(),
            "-m",
            "Publish shared policy",
        ],
    );
    let published = json(&published);
    assert_eq!(published["status"], "pushed");
    assert_eq!(published["head"], "main");
    assert_eq!(published["review"]["pull_request"], "required");
    assert_eq!(published["review"]["managed_by"], "agent");
    assert_eq!(published["review"]["merge_authority"], "user");
    assert_eq!(git(&worktree, ["rev-parse", "HEAD"]).stdout, main_before);
    assert_eq!(git(&worktree, ["ls-files", "--stage"]).stdout, index_before);
    assert_eq!(
        git(&worktree, ["worktree", "list", "--porcelain"]).stdout,
        worktrees_before
    );
    let commit = published["commit_oid"].as_str().unwrap();
    assert!(
        git_unchecked(
            &fixture.shared,
            ["cat-file", "-e", &format!("{commit}:shared-policy.md")],
        )
        .status
        .success()
    );
    assert!(
        !git_unchecked(
            &worktree,
            ["cat-file", "-e", &format!("{commit}:unrelated-overlay.txt")]
        )
        .status
        .success()
    );
    assert_eq!(
        std::fs::read_to_string(worktree.join("unrelated-overlay.txt")).unwrap(),
        "another task's unpublished bytes\n"
    );

    std::fs::remove_file(worktree.join("shared-policy.md")).unwrap();
    let removed = workspace(
        &worktree,
        [
            "publish",
            "--manifest",
            manifest.to_str().unwrap(),
            "-m",
            "Remove shared policy",
        ],
    );
    let removed = json(&removed);
    assert_eq!(removed["status"], "pushed");
    assert_eq!(
        removed["changed_paths"],
        serde_json::json!(["shared-policy.md"])
    );
    let removed_commit = removed["commit_oid"].as_str().unwrap();
    assert!(
        !git_unchecked(
            &fixture.shared,
            [
                "cat-file",
                "-e",
                &format!("{removed_commit}:shared-policy.md")
            ],
        )
        .status
        .success()
    );
    let clean = workspace(
        &worktree,
        ["plan", "--manifest", manifest.to_str().unwrap()],
    );
    assert_eq!(json(&clean)["status"], "no_changes");
}

#[test]
fn infrastructure_plan_and_publish_require_main_refresh_before_replacing_upstream_scopes() {
    let fixture = GitFixture::new();
    workspace(&fixture.seed, ["manage"]);
    std::fs::write(fixture.seed.join("policy.md"), "original upstream policy\n").unwrap();
    fixture.commit_seed("Initialize shared policy");
    fixture.clone_shared();
    let created = json(&workspace(
        &fixture.shared,
        [
            "task",
            "create",
            "change-policy",
            "--kind",
            "infrastructure",
            "--title",
            "Change shared policy",
            "--purpose",
            "Protect concurrent shared-policy changes",
            "--scope",
            "policy.md",
            "--scope-note",
            "The user requested this shared policy change",
        ],
    ));
    let manifest = created["manifest"].as_str().unwrap();
    std::fs::write(fixture.shared.join("policy.md"), "local proposed policy\n").unwrap();
    let main_before = git(&fixture.shared, ["rev-parse", "HEAD"]).stdout;
    let index_before = git(&fixture.shared, ["ls-files", "--stage"]).stdout;
    std::fs::write(
        fixture.seed.join("policy.md"),
        "concurrent upstream policy\n",
    )
    .unwrap();
    fixture.commit_seed("Update policy before infrastructure publication");
    for args in [
        vec!["plan", "--manifest", manifest],
        vec![
            "publish",
            "--manifest",
            manifest,
            "-m",
            "Attempt to publish stale policy",
        ],
    ] {
        let refused = workspace_unchecked(&fixture.shared, args);
        assert_eq!(refused.status.code(), Some(2));
        assert!(String::from_utf8_lossy(&refused.stderr).contains("refresh"));
        assert_eq!(
            git(&fixture.shared, ["rev-parse", "HEAD"]).stdout,
            main_before
        );
        assert_eq!(
            git(&fixture.shared, ["ls-files", "--stage"]).stdout,
            index_before
        );
        assert_eq!(
            std::fs::read_to_string(fixture.shared.join("policy.md")).unwrap(),
            "local proposed policy\n"
        );
        assert!(
            !git_unchecked(
                &fixture.remote,
                [
                    "show-ref",
                    "--verify",
                    "refs/heads/codex/infra-change-policy"
                ]
            )
            .status
            .success()
        );
        assert_eq!(
            String::from_utf8(git(&fixture.remote, ["show", "main:policy.md"]).stdout).unwrap(),
            "concurrent upstream policy\n"
        );
    }
}

#[test]
fn setup_verifies_native_storage_without_python_or_directory_changes() {
    let fixture = GitFixture::new();
    let runtime = fixture.root.join("former-runtime");
    std::fs::create_dir(&runtime).unwrap();
    std::fs::write(runtime.join("sentinel"), "preserve\n").unwrap();
    for dry_run in [true, false] {
        let mut args = vec!["setup", "--runtime-dir", runtime.to_str().unwrap()];
        if dry_run {
            args.push("--dry-run");
        }
        let output = binary_command()
            .args(args)
            .current_dir(&fixture.root)
            .env("WORKSPACE_MGR_FORMAT", "json")
            .env("WORKSPACE_MGR_BOOTSTRAP_PYTHON", "/does-not-exist/python")
            .env("WORKSPACE_MGR_STORAGE_DVC", "/does-not-exist/dvc")
            .env("WORKSPACE_MGR_STORAGE_PYTHON", "/does-not-exist/python")
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let report = json(&output);
        assert_eq!(
            report["storage_runtime"],
            format!("native Rust {}", env!("CARGO_PKG_VERSION"))
        );
        assert_eq!(report["runtime_dir"], "");
        assert_eq!(
            std::fs::read_to_string(runtime.join("sentinel")).unwrap(),
            "preserve\n"
        );
        assert_eq!(std::fs::read_dir(&runtime).unwrap().count(), 1);
    }
}

