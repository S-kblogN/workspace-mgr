    let imported = json(&imported);
    assert_eq!(imported["status"], "managed");
    assert!(
        imported["actions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|action| action["path"] == ".gitignore" && action["action"] == "update"),
        "{imported}"
    );
